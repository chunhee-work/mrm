#!/usr/bin/env node
// Copies the playbook (the owner's rules) into the website and the worker, so the AI there reads the same rules as the
// Mac tools do. Vercel builds from web/ only, so the copy is committed and CI runs `--check`.
//   node scripts/sync-playbook.mjs           write the copies
//   node scripts/sync-playbook.mjs --check   exit 1 when a copy differs from the repo (CI)
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
// The playbook files the site's AI prompts use (01 documents, 03 + 11 photo names, 06 upload, 07 + 08 Step 2, 10 car models).
export const FILES = [
  "01-read-documents.md", "03-photo-naming.md", "06-upload-docs-and-photos.md", "07-select-parts-and-labour.md",
  "08-estimate-details.md", "10-car-models.md", "11-car-logos.md",
];
const NAMES_SRC = "tools/naming-desk/names.json";
const RULES_SRC = "playbook/photo-rules.json";
const WEB_TS = "web/src/lib/playbook/generated.ts";
const WEB_RULES = "web/src/lib/playbook/photo-rules.ts";
const WEB_NAMES = "web/src/lib/part-names.json";
const WORKER_DIR = "worker/autopilot_worker/playbook";

const sha = (s) => createHash("sha256").update(s).digest("hex");
const read = (p) => readFileSync(join(ROOT, p), "utf8");

export function build() {
  const md = Object.fromEntries(FILES.map((f) => [f, read(`playbook/${f}`)]));
  const names = read(NAMES_SRC);
  const rules = read(RULES_SRC);
  const hashes = { ...Object.fromEntries(FILES.map((f) => [f, sha(md[f])])), "names.json": sha(names), "photo-rules.json": sha(rules) };
  // version = hash of the content, so a copy never "drifts" without the version changing. The repo commit is added at run time.
  const version = sha(Object.keys(hashes).sort().map((k) => `${k}:${hashes[k]}`).join("\n")).slice(0, 12);
  const manifest = { version, files: hashes };
  const out = new Map();
  out.set(WEB_NAMES, names);
  out.set(
    WEB_TS,
    `// GENERATED by scripts/sync-playbook.mjs from playbook/*.md. Do not edit; CI fails when it differs from the repo.\n` +
      `export const PLAYBOOK_VERSION = ${JSON.stringify(version)};\n` +
      `export const PLAYBOOK_MANIFEST = ${JSON.stringify(manifest)} as const;\n` +
      `export const PLAYBOOK_FILES: Record<string, string> = ${JSON.stringify(md, null, 1)};\n`,
  );
  // small and client-safe: the desk (browser) imports this one, never generated.ts (about 200 KB of prose)
  out.set(
    WEB_RULES,
    `// GENERATED by scripts/sync-playbook.mjs from playbook/photo-rules.json. Do not edit.\n` +
      `export const PHOTO_RULES = ${rules.trim().replace(/^\{\s*"_about":[^\n]*\n/, "{\n")} as const;\n`,
  );
  for (const f of FILES) out.set(`${WORKER_DIR}/${f}`, md[f]);
  out.set(`${WORKER_DIR}/names.json`, names);
  out.set(`${WORKER_DIR}/photo-rules.json`, rules);
  out.set(`${WORKER_DIR}/manifest.json`, JSON.stringify(manifest, null, 1) + "\n");
  return out;
}

export function diff(out = build()) {
  const bad = [];
  for (const [p, content] of out) if (!existsSync(join(ROOT, p)) || read(p) !== content) bad.push(p);
  const dir = join(ROOT, WORKER_DIR);
  if (existsSync(dir)) for (const f of readdirSync(dir)) if (!out.has(`${WORKER_DIR}/${f}`)) bad.push(`${WORKER_DIR}/${f} (stale)`);
  return bad;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = build();
  if (process.argv.includes("--check")) {
    const bad = diff(out);
    if (bad.length) { console.error("Playbook copies differ from the repo. Run `node scripts/sync-playbook.mjs` and commit:\n  " + bad.join("\n  ")); process.exit(1); }
    console.log("playbook copies match the repo");
  } else {
    mkdirSync(join(ROOT, WORKER_DIR), { recursive: true });
    mkdirSync(dirname(join(ROOT, WEB_TS)), { recursive: true });
    for (const f of readdirSync(join(ROOT, WORKER_DIR))) if (!out.has(`${WORKER_DIR}/${f}`)) rmSync(join(ROOT, WORKER_DIR, f));
    for (const [p, c] of out) writeFileSync(join(ROOT, p), c);
    console.log(`wrote ${out.size} files, version ${JSON.parse(out.get(`${WORKER_DIR}/manifest.json`)).version}`);
  }
}
