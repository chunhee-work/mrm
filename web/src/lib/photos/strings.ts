export const PHOTO_DICTS: Record<Lang, Dict> = { en, zh, ms };
export type PT = (key: string, vars?: Record<string, string | number>) => string;
export function photoT(lang: Lang): PT {
  return (key, vars) => {
    return fill(PHOTO_DICTS[lang][key] ?? en[key] ?? key, vars);
  };
}
