export const LANGS = ["en", "zh", "ms"] as const;
export type Lang = (typeof LANGS)[number];
export const LANG_LABEL: Record<Lang, string> = { en: "English", zh: "中文", ms: "Bahasa Melayu" };
export const LANG_SHORT: Record<Lang, string> = { en: "EN", zh: "中文", ms: "BM" };
export const DEFAULT_LANG: Lang = "en";
export const MIN_PASSWORD = 8;

export function normLang(v: string | undefined | null): Lang {
  return (LANGS as readonly string[]).includes(v ?? "") ? (v as Lang) : DEFAULT_LANG;
}
export function htmlLang(l: Lang): string {
  return l === "zh" ? "zh-CN" : l;
}
export function localeOf(l: Lang): string {
  return l === "zh" ? "zh-CN" : l === "ms" ? "ms-MY" : "en-MY";
}

